def estimate_cost(response_usage, model: str) -> float:
    """Estimate the USD cost of one OpenAI chat completion from its usage stats."""
    pricing = PRICING.get(model)
    if pricing is None:
        logger.warning("No pricing data for model '%s'; cost estimate is $0.00", model)
        return 0.0

    cost_input = (response_usage.prompt_tokens / 1_000_000) * pricing["in"]
    cost_output = (response_usage.completion_tokens / 1_000_000) * pricing["out"]
    return cost_input + cost_output
